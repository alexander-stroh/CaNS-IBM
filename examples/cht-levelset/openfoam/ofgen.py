"""
OpenFOAM (ESI v2412) multi-region CHT counterparts of the CaNS validation cases (body-fitted meshes, one region per
material; chtMultiRegionFoam for transients, chtMultiRegionSimpleFoam for steady states).
Same non-dimensional problem as the CaNS runs: rho = cp = 1 and mu = nu (fluid), Pr_f = 1 (kappa_f = mu),
solid kappa_s = K kappa_f, (rho cp)_s = C (rho = 1, cp = C); constant pressure gradient (vectorSemiImplicitSource on
U) and uniform heat source q0 = 1 in the fluid (scalarSemiImplicitSource on h); temperatures offset by T0 = 300
(T_OF = T + T0; linear problem, constant properties). Tested with OpenFOAM v2412 (ESI). Coordinates as in CaNS: x periodic (cyclic), y empty (2D),
z wall-normal. Regions from blockMesh cell zones (splitMeshRegions -cellZones).
"""
from pathlib import Path
import numpy as np

T0 = 300.
P0 = 1e5

def hdr(cls, obj, loc=None):
    l = f'    location    "{loc}";\n' if loc else ''
    return ('/*--------------------------------*- C++ -*----------------------------------*\\\n'
            '  OpenFOAM v2412, generated by examples/cht-levelset/openfoam/make_cases.py\n'
            '\\*---------------------------------------------------------------------------*/\n'
            f'FoamFile\n{{\n    version     2.0;\n    format      ascii;\n    class       {cls};\n{l}    object      {obj};\n}}\n\n')

def put(path, cls, obj, body, loc=None):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(hdr(cls, obj, loc) + body + '\n// ************************************************************************* //\n')

# ------------------------------------------------------------------------------------------------ physics

def thermo_fluid(mu):
    return f"""thermoType
{{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState rhoConst;
    specie          specie;
    energy          sensibleEnthalpy;
}}
mixture
{{
    specie          {{ molWeight 1; }}
    equationOfState {{ rho 1; }}
    thermodynamics  {{ Cp 1; Hf 0; }}
    transport       {{ mu {mu!r}; Pr 1; }}
}}
"""

def thermo_solid(kappa, cp):
    return f"""thermoType
{{
    type            heSolidThermo;
    mixture         pureMixture;
    transport       constIso;
    thermo          hConst;
    equationOfState rhoConst;
    specie          specie;
    energy          sensibleEnthalpy;
}}
mixture
{{
    specie          {{ molWeight 1; }}
    equationOfState {{ rho 1; }}
    thermodynamics  {{ Cp {cp!r}; Hf 0; }}
    transport       {{ kappa {kappa!r}; }}
}}
"""

def fvoptions_fluid(bforce, q0=1.):
    return f"""pressureGradient
{{
    type            vectorSemiImplicitSource;
    selectionMode   all;
    volumeMode      specific;
    sources         {{ U (({bforce!r} 0 0) 0); }}
}}
heatSource
{{
    type            scalarSemiImplicitSource;
    selectionMode   all;
    volumeMode      specific;
    sources         {{ h ({q0!r} 0); }}
}}
"""

# ------------------------------------------------------------------------------------------------ fields

def bf(entries):
    return 'boundaryField\n{\n' + ''.join(f'    {k}\n    {{\n' + ''.join(f'        {l}\n' for l in v) + '    }\n' for k, v in entries) + '}\n'

PER = [('"(left|right)"', ['type cyclic;']), ('"(front|back)"', ['type empty;'])]

def fields_fluid(case, outer_walls):
    """outer_walls: patch regex of the fluid's own (non-interface) walls with T = T0, or None"""
    d = case/'0'/'fluid'
    U = [*PER, ('".*_to_.*"', ['type noSlip;'])] + ([(outer_walls, ['type noSlip;'])] if outer_walls else [])
    put(d/'U', 'volVectorField', 'U', 'dimensions [0 1 -1 0 0 0 0];\ninternalField uniform (0 0 0);\n' + bf(U))
    T = [*PER, ('".*_to_.*"', ['type compressible::turbulentTemperatureCoupledBaffleMixed;', 'Tnbr T;',
                                'kappaMethod fluidThermo;', f'value uniform {T0};'])]
    if outer_walls: T.append((outer_walls, ['type fixedValue;', f'value uniform {T0};']))
    put(d/'T', 'volScalarField', 'T', f'dimensions [0 0 0 1 0 0 0];\ninternalField uniform {T0};\n' + bf(T))
    pr = [('".*"', ['type fixedFluxPressure;', f'value uniform {P0};']), *PER]   # later regex entries take precedence
    put(d/'p_rgh', 'volScalarField', 'p_rgh', f'dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform {P0};\n' + bf(pr))
    put(d/'p', 'volScalarField', 'p', f'dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform {P0};\n' +
        bf([('".*"', ['type calculated;', f'value uniform {P0};']), *PER]))

def fields_solid(case, region, outer_walls):
    d = case/'0'/region
    T = [*PER, ('".*_to_.*"', ['type compressible::turbulentTemperatureCoupledBaffleMixed;', 'Tnbr T;',
                                'kappaMethod solidThermo;', f'value uniform {T0};'])]
    if outer_walls: T.append((outer_walls, ['type fixedValue;', f'value uniform {T0};']))
    put(d/'T', 'volScalarField', 'T', f'dimensions [0 0 0 1 0 0 0];\ninternalField uniform {T0};\n' + bf(T))
    put(d/'p', 'volScalarField', 'p', f'dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform {P0};\n' +
        bf([('".*"', ['type calculated;', f'value uniform {P0};']), *PER]))

# ------------------------------------------------------------------------------------------------ numerics

def schemes_fluid(steady):
    ddt = 'steadyState' if steady else 'backward'
    conv = 'bounded Gauss linear' if steady else 'Gauss linear'
    return f"""ddtSchemes      {{ default {ddt}; }}
gradSchemes     {{ default Gauss linear; }}
divSchemes
{{
    default         none;
    div(phi,U)      {conv};
    div(phi,K)      {conv};
    div(phi,h)      {conv};
    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear corrected; }}
interpolationSchemes {{ default linear; }}
snGradSchemes   {{ default corrected; }}
"""

def schemes_solid(steady):
    return f"""ddtSchemes      {{ default {'steadyState' if steady else 'backward'}; }}
gradSchemes     {{ default Gauss linear; }}
divSchemes      {{ default none; }}
laplacianSchemes {{ default none; laplacian(alpha,h) Gauss linear corrected; }}
interpolationSchemes {{ default linear; }}
snGradSchemes   {{ default corrected; }}
"""

NOUTER = 1                                        # PIMPLE outer correctors (region coupling iterations per step)

def solution_fluid(steady, nnonorth):
    algo = (f"""SIMPLE
{{
    momentumPredictor yes;
    nNonOrthogonalCorrectors {nnonorth};
    pRefCell        0;
    pRefValue       {P0};
    residualControl {{ p_rgh 1e-6; U 1e-10; h 1e-11; }}
}}
relaxationFactors
{{
    fields          {{ rho 1; p_rgh 0.7; }}
    equations       {{ U 0.5; h 0.9; }}
}}
""" if steady else f"""PIMPLE
{{
    momentumPredictor yes;
    nOuterCorrectors {NOUTER};
    nCorrectors     2;
    nNonOrthogonalCorrectors {nnonorth};
    pRefCell        0;
    pRefValue       {P0};
}}
relaxationFactors {{ equations {{ ".*" 1; }} }}
""")
    tolp, tolu = (1e-12, 1e-12) if steady else (1e-6, 1e-10)     # transient: GAMG stalls at ~6e-7 (p ~ 1e5)
    return f"""solvers
{{
    "rho.*"         {{ solver PCG; preconditioner DIC; tolerance 0; relTol 0; }}
    p_rgh           {{ solver GAMG; smoother GaussSeidel; tolerance {tolp}; relTol 0.01; maxIter 200; }}
    p_rghFinal      {{ $p_rgh; relTol 0; }}
    "(U|h)"         {{ solver PBiCGStab; preconditioner DILU; tolerance {tolu}; relTol {0.01 if steady else 0}; }}
    "(U|h)Final"    {{ $U; relTol 0; }}
}}
""" + algo

def solution_solid(steady, nnonorth):
    return f"""solvers
{{
    h               {{ solver PCG; preconditioner DIC; tolerance {1e-12 if steady else 1e-10}; relTol {0.01 if steady else 0}; }}
    hFinal          {{ $h; relTol 0; }}
}}
{'SIMPLE' if steady else 'PIMPLE'} {{ nNonOrthogonalCorrectors {nnonorth}; }}
relaxationFactors {{ equations {{ h 1; }} }}
"""

def control(app, end, dt, write, adjust=False, maxco=0.5, functions=''):
    return f"""application     {app};
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {end!r};
deltaT          {dt!r};
writeControl    {'adjustable' if adjust else ('timeStep' if app.endswith('SimpleFoam') else 'runTime')};
writeInterval   {write!r};
purgeWrite      {1 if app.endswith('SimpleFoam') else 0};
writeFormat     ascii;
writePrecision  12;
writeCompression off;
timeFormat      general;
timePrecision   10;
runTimeModifiable no;
adjustTimeStep  {'yes' if adjust else 'no'};
maxCo           {maxco};
maxDi           1000;
functions
{{
{functions}}}
"""

def write_common(case, fluid_mu, bforce, solids, steady, nnonorth, ctrl):
    """solids: dict region -> (kappa, cp)"""
    put(case/'constant'/'regionProperties', 'dictionary', 'regionProperties',
        f"regions\n(\n    fluid (fluid)\n    solid ({' '.join(solids)})\n);\n")
    put(case/'constant'/'g', 'uniformDimensionedVectorField', 'g', 'dimensions [0 1 -2 0 0 0 0];\nvalue (0 0 0);\n')
    put(case/'constant'/'fluid'/'thermophysicalProperties', 'dictionary', 'thermophysicalProperties', thermo_fluid(fluid_mu))
    put(case/'constant'/'fluid'/'turbulenceProperties', 'dictionary', 'turbulenceProperties', 'simulationType laminar;\n')
    put(case/'constant'/'fluid'/'fvOptions', 'dictionary', 'fvOptions', fvoptions_fluid(bforce))
    put(case/'system'/'fluid'/'fvSchemes', 'dictionary', 'fvSchemes', schemes_fluid(steady))
    put(case/'system'/'fluid'/'fvSolution', 'dictionary', 'fvSolution', solution_fluid(steady, nnonorth))
    for r, (kappa, cp) in solids.items():
        put(case/'constant'/r/'thermophysicalProperties', 'dictionary', 'thermophysicalProperties', thermo_solid(kappa, cp))
        put(case/'system'/r/'fvSchemes', 'dictionary', 'fvSchemes', schemes_solid(steady))
        put(case/'system'/r/'fvSolution', 'dictionary', 'fvSolution', solution_solid(steady, nnonorth))
    put(case/'system'/'controlDict', 'dictionary', 'controlDict', ctrl)
    put(case/'system'/'fvSchemes', 'dictionary', 'fvSchemes', schemes_solid(steady))
    # chtMultiRegionFoam reads the region-coupling (outer) iterations from the case-wide system/fvSolution
    put(case/'system'/'fvSolution', 'dictionary', 'fvSolution', f'PIMPLE {{ nOuterCorrectors {NOUTER}; }}\nSIMPLE {{}}\n')

# ------------------------------------------------------------------------------------------------ blockMesh

def blockmesh(vertices, blocks, edges, patches, ly):
    """vertices: list of (x, z) in the x-z plane (extruded to y = 0, ly: index i -> i (y=0), i + n (y=ly));
    blocks: (zone, (v0, v1, v2, v3) counter-clockwise in x-z seen from -y, (nx, nz), (gx, gz));
    edges: (v_a, v_b, kind, points (x, z) list) on the x-z plane (duplicated at y = ly);
    patches: name -> (type, [(va, vb)] boundary edges in the x-z plane), plus front/back (empty) automatic"""
    n = len(vertices)
    V = ''.join(f'    ({float(x)!r} 0 {float(z)!r})\n' for x, z in vertices) + ''.join(f'    ({float(x)!r} {ly!r} {float(z)!r})\n' for x, z in vertices)
    B = ''
    for zone, (a, b, c, d), (nx, nz), (gx, gz) in blocks:
        # hex ordering (x1, x2, x3) = (along a->b, along a->d, y): bottom face a b c d at y = 0? use (a b b+n a+n) etc.
        B += f'    hex ({a} {b} {b + n} {a + n} {d} {c} {c + n} {d + n}) {zone} ({nx} 1 {nz}) simpleGrading ({gx!r} 1 {gz!r})\n'
    E = ''
    for a, b, kind, pts in edges:
        for off in (0, n):
            P = ' '.join(f'({float(x)!r} {(ly if off else 0.)!r} {float(z)!r})' for x, z in pts)
            E += f'    {kind} {a + off} {b + off} ' + (f'({P})' if kind != 'arc' else P) + '\n'
    P = ''
    for name, (typ, faces, extra) in patches.items():
        F = ''.join(f'            ({a} {b} {b + n} {a + n})\n' for a, b in faces)
        P += f'    {name}\n    {{\n        type {typ};\n{extra}        faces\n        (\n{F}        );\n    }}\n'
    front = ''.join(f'            ({a} {d} {c} {b})\n' for _, (a, b, c, d), _, _ in blocks)
    back = ''.join(f'            ({a + n} {b + n} {c + n} {d + n})\n' for _, (a, b, c, d), _, _ in blocks)
    P += f'    front\n    {{\n        type empty;\n        faces\n        (\n{front}        );\n    }}\n'
    P += f'    back\n    {{\n        type empty;\n        faces\n        (\n{back}        );\n    }}\n'
    return (f'scale 1;\n\nvertices\n(\n{V});\n\nblocks\n(\n{B});\n\nedges\n(\n{E});\n\nboundary\n(\n{P});\n\n'
            'mergePatchPairs\n(\n);\n')

ALLRUN = """#!/bin/bash
# mesh, split into regions and run ({app}) on NP = {np} cores; log files log.*
cd "${{0%/*}}" || exit 1
[ -n "$WM_PROJECT_DIR" ] || source ${{FOAM_BASHRC:-/usr/lib/openfoam/openfoam2412/etc/bashrc}}
NP={np}
blockMesh > log.blockMesh 2>&1 || exit 1
splitMeshRegions -cellZones -overwrite > log.splitMeshRegions 2>&1 || exit 1
for r in {regions}; do checkMesh -region $r -constant > log.checkMesh.$r 2>&1; done
if [ $NP -gt 1 ]; then
  decomposePar -allRegions -force > log.decomposePar 2>&1 || exit 1
  mpirun -np $NP --bind-to none {app} -parallel > log.{app} 2>&1; rc=$?
  reconstructPar -allRegions {recon} > log.reconstructPar 2>&1
else
  {app} > log.{app} 2>&1; rc=$?
fi
for r in {regions}; do
  postProcess -func writeCellCentres -region $r -latestTime > log.cc.$r 2>&1
  postProcess -func writeCellVolumes -region $r -latestTime > log.vol.$r 2>&1
done
echo "exit $rc" >> log.{app}
"""

DECOMP = """numberOfSubdomains {np};
method          scotch;
"""

def write_allrun(case, app, regions, np_=1, recon='-latestTime'):
    p = case/'Allrun'; p.write_text(ALLRUN.format(app=app, regions=' '.join(regions), np=np_, recon=recon)); p.chmod(0o755)
    if np_ > 1:                                   # decomposePar -allRegions reads system/<region>/decomposeParDict
        for d in [case/'system'] + [case/'system'/r for r in regions]:
            put(d/'decomposeParDict', 'dictionary', 'decomposeParDict', DECOMP.format(np=np_))
