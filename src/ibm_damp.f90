! -
!
! damping of the x odd-even (2 dx) mode near the immersed boundary
!
! The 2nd-order central x advection does not see the x Nyquist mode (face value 0.5*(f(i)+f(i+1)) = 0), so
! grid-scale noise generated by the immersed boundary is neither advected nor damped (only by viscosity).
! A fourth-difference (hyperviscosity) term, scaled with the local |u| and active only near the boundary,
!   df/dt += -eps*sigma*|u|*dx^3*d4f/dx4 = -eps*sigma*|u|*(f(i-2)-4f(i-1)+6f(i)-4f(i+1)+f(i+2))/dx
! damps the mode (transfer function sin^4(k dx/2): 1 at 2 dx, 0.021 at 8 dx). sigma = 1 for phi <= d(1)*dx,
! cosine ramp to 0 at phi = d(2)*dx, phi = level set (> 0 in the fluid). Third-order upwinding would correspond
! to eps = 1/12 everywhere. x must not be decomposed (periodic stencil wraps inside the pencil).
!
! -
module mod_ibm_damp
  use mpi
  use mod_types
  implicit none
  private
  public ibm_damp_init,ibm_damp_mom,ibm_damp_scal
  real(rp), allocatable, dimension(:,:,:) :: sig_u,sig_v,sig_w,sig_s
  contains
  subroutine ibm_damp_init(n,ng,dx,d,phi_s,phi_u,phi_v,phi_w,myid)
    integer , intent(in), dimension(3) :: n,ng
    real(rp), intent(in) :: dx,d(2)
    real(rp), intent(in), dimension(0:,0:,0:) :: phi_s,phi_u,phi_v,phi_w
    integer , intent(in) :: myid
    integer :: ierr
    real(rp) :: cnt(4)
    if(n(1) /= ng(1)) then
      if(myid == 0) print*, 'ERROR: is_ibm_damp needs an undecomposed x direction (n(1) = ng(1)).'
      call MPI_FINALIZE(ierr)
      error stop
    end if
    allocate(sig_u(n(1),n(2),n(3)),sig_v(n(1),n(2),n(3)),sig_w(n(1),n(2),n(3)),sig_s(n(1),n(2),n(3)))
    call weight(phi_u,sig_u); call weight(phi_v,sig_v); call weight(phi_w,sig_w); call weight(phi_s,sig_s)
    cnt(:) = [sum(sig_u),sum(sig_v),sum(sig_w),sum(sig_s)]
    call MPI_ALLREDUCE(MPI_IN_PLACE,cnt,4,MPI_REAL_RP,MPI_SUM,MPI_COMM_WORLD,ierr)
    if(myid == 0) print '(a,4f8.4)', ' *** IBM x damping: weighted volume fraction (u, v, w, s): ',cnt(:)/product(1._rp*ng(:))
    !$acc enter data copyin(sig_u,sig_v,sig_w,sig_s)
  contains
    subroutine weight(phi,sig)
      real(rp), intent(in ), dimension(0:,0:,0:) :: phi
      real(rp), intent(out), dimension(:,:,:) :: sig
      integer :: i,j,k
      real(rp) :: r
      do k=1,n(3)
        do j=1,n(2)
          do i=1,n(1)
            r = (phi(i,j,k)/dx - d(1))/(d(2) - d(1))
            sig(i,j,k) = 0.5_rp*(1._rp + cos(acos(-1._rp)*min(max(r,0._rp),1._rp)))
          end do
        end do
      end do
    end subroutine weight
  end subroutine ibm_damp_init
  !
  subroutine ibm_damp_mom(n,dxi,eps,u,v,w,dudt,dvdt,dwdt)
    integer , intent(in) :: n(3)
    real(rp), intent(in) :: dxi,eps
    real(rp), intent(in   ), dimension(0:,0:,0:) :: u,v,w
    real(rp), intent(inout), dimension(:,:,:) :: dudt,dvdt,dwdt
    integer :: i,j,k,im2,im1,ip1,ip2
    real(rp) :: c,uv,uw
    c = eps*dxi
    !$acc parallel loop collapse(3) default(present) private(im2,im1,ip1,ip2,uv,uw) async(1)
    !$OMP PARALLEL DO   COLLAPSE(3) DEFAULT(shared)  PRIVATE(im2,im1,ip1,ip2,uv,uw)
    do k=1,n(3)
      do j=1,n(2)
        do i=1,n(1)
          im2 = modulo(i-3,n(1))+1; im1 = modulo(i-2,n(1))+1
          ip1 = modulo(i  ,n(1))+1; ip2 = modulo(i+1,n(1))+1
          uv = 0.25_rp*(u(im1,j,k)+u(i,j,k)+u(im1,j+1,k)+u(i,j+1,k))   ! u at the v point
          uw = 0.25_rp*(u(im1,j,k)+u(i,j,k)+u(im1,j,k+1)+u(i,j,k+1))   ! u at the w point
          dudt(i,j,k) = dudt(i,j,k) - c*sig_u(i,j,k)*abs(u(i,j,k))* &
                        (u(im2,j,k)-4._rp*u(im1,j,k)+6._rp*u(i,j,k)-4._rp*u(ip1,j,k)+u(ip2,j,k))
          dvdt(i,j,k) = dvdt(i,j,k) - c*sig_v(i,j,k)*abs(uv)* &
                        (v(im2,j,k)-4._rp*v(im1,j,k)+6._rp*v(i,j,k)-4._rp*v(ip1,j,k)+v(ip2,j,k))
          dwdt(i,j,k) = dwdt(i,j,k) - c*sig_w(i,j,k)*abs(uw)* &
                        (w(im2,j,k)-4._rp*w(im1,j,k)+6._rp*w(i,j,k)-4._rp*w(ip1,j,k)+w(ip2,j,k))
        end do
      end do
    end do
  end subroutine ibm_damp_mom
  !
  subroutine ibm_damp_scal(n,dxi,eps,u,s,dsdt)
    integer , intent(in) :: n(3)
    real(rp), intent(in) :: dxi,eps
    real(rp), intent(in   ), dimension(0:,0:,0:) :: u,s
    real(rp), intent(inout), dimension(:,:,:) :: dsdt
    integer :: i,j,k,im2,im1,ip1,ip2
    real(rp) :: c
    c = eps*dxi
    !$acc parallel loop collapse(3) default(present) private(im2,im1,ip1,ip2) async(1)
    !$OMP PARALLEL DO   COLLAPSE(3) DEFAULT(shared)  PRIVATE(im2,im1,ip1,ip2)
    do k=1,n(3)
      do j=1,n(2)
        do i=1,n(1)
          im2 = modulo(i-3,n(1))+1; im1 = modulo(i-2,n(1))+1
          ip1 = modulo(i  ,n(1))+1; ip2 = modulo(i+1,n(1))+1
          dsdt(i,j,k) = dsdt(i,j,k) - c*sig_s(i,j,k)*abs(0.5_rp*(u(im1,j,k)+u(i,j,k)))* &
                        (s(im2,j,k)-4._rp*s(im1,j,k)+6._rp*s(i,j,k)-4._rp*s(ip1,j,k)+s(ip2,j,k))
        end do
      end do
    end do
  end subroutine ibm_damp_scal
end module mod_ibm_damp
